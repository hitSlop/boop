#!/usr/bin/env bash
set -euo pipefail

# Bootstrap an Ubuntu Linux worker (Boat.dev or generic SSH) for Boop iOS cross-builds.
# Installs Swift 6.4 (via Swiftly), xtool 2.0.0-beta.1 (extracted AppImage), llvm-lipo,
# and the lightweight Linux build shims (actool, metal/metallib, Apple ld64.lld clang wrapper,
# bitcode_strip) proven in Phase 0.
#
# Run on the remote Linux VM (idempotent).

export DEBIAN_FRONTEND=noninteractive
mkdir -p "$HOME/.local/share/boop" "$HOME/.local/bin"

echo "==> Installing system packages (libcurl, libxml2, ncurses, llvm, rsync)..."
sudo apt-get update -qq
sudo apt-get install -y -qq libcurl4-openssl-dev libxml2-dev libncurses6 llvm rsync util-linux >/dev/null

echo "==> Installing Swiftly + Swift 6.4..."
if ! command -v swiftly >/dev/null 2>&1 && [ ! -x "$HOME/.local/share/swiftly/bin/swiftly" ]; then
  curl -fsSL "https://download.swift.org/swiftly/linux/swiftly-$(uname -m).tar.gz" -o /tmp/swiftly.tar.gz
  tar -xzf /tmp/swiftly.tar.gz -C /tmp
  /tmp/swiftly init --assume-yes --no-modify-profile --skip-install
  rm -f /tmp/swiftly.tar.gz /tmp/swiftly
fi
export PATH="$HOME/.local/share/swiftly/bin:$HOME/.local/bin:$PATH"
if ! swift --version >/dev/null 2>&1; then
  swiftly install 6.4 --assume-yes
  swiftly use 6.4
  swiftly link
fi
swift --version

echo "==> Installing xtool 2.0.0-beta.1 (extracted AppImage)..."
XTOOL_VER="2.0.0-beta.1"
XTOOL_DIR="$HOME/.local/share/boop/xtool-$XTOOL_VER"
ARCH="$(uname -m)"
if [ ! -x "$XTOOL_DIR/AppRun" ]; then
  mkdir -p "/tmp/xt-$XTOOL_VER"
  curl -fsSL "https://github.com/xtool-org/xtool/releases/download/$XTOOL_VER/xtool-${ARCH}.AppImage" -o "/tmp/xt-$XTOOL_VER/xtool.AppImage"
  chmod +x "/tmp/xt-$XTOOL_VER/xtool.AppImage"
  (cd "/tmp/xt-$XTOOL_VER" && ./xtool.AppImage --appimage-extract >/dev/null)
  rm -rf "$XTOOL_DIR"
  mv "/tmp/xt-$XTOOL_VER/squashfs-root" "$XTOOL_DIR"
  rm -rf "/tmp/xt-$XTOOL_VER"
fi
ln -sf "$XTOOL_DIR/AppRun" "$HOME/.local/bin/xtool2"
ln -sf "$XTOOL_DIR/AppRun" "$HOME/.local/bin/xtool"

echo "==> Linking llvm-lipo -> ~/.local/bin/lipo..."
LIPO_BIN="$(command -v llvm-lipo || find /usr/bin -name 'llvm-lipo*' 2>/dev/null | head -n 1)"
if [ -n "$LIPO_BIN" ]; then
  ln -sf "$LIPO_BIN" "$HOME/.local/bin/lipo"
fi

echo "==> Installing actool & metal/metallib Linux shims (real assets/Metal compiled locally on Mac)..."
ACTOOL_BUNDLE_VER="${BOOP_ACTOOL_BUNDLE_VERSION:-23210}"
ACTOOL_SHORT_VER="${BOOP_ACTOOL_SHORT_VERSION:-16.2}"
cat > "$HOME/.local/bin/actool" <<PY
#!/usr/bin/env python3
import os, plistlib, sys

args = sys.argv[1:]
if "--version" in args:
    sys.stdout.buffer.write(plistlib.dumps({
        "com.apple.actool.version": {
            "bundle-version": "${ACTOOL_BUNDLE_VER}",
            "short-bundle-version": "${ACTOOL_SHORT_VER}",
        }
    }))
    sys.exit(0)

if "--print-asset-tag-combinations" in args:
    sys.stdout.buffer.write(plistlib.dumps({
        "com.apple.actool.asset-tag-combinations": []
    }))
    sys.exit(0)

def opt_val(*flags):
    for flag in flags:
        if flag in args:
            i = args.index(flag)
            if i + 1 < len(args):
                return args[i + 1]
    return None

out_dir = opt_val("--compile")
if out_dir:
    os.makedirs(out_dir, exist_ok=True)

partial_plist = opt_val("--output-partial-info-plist")
if partial_plist:
    os.makedirs(os.path.dirname(os.path.abspath(partial_plist)), exist_ok=True)
    with open(partial_plist, "wb") as f:
        plistlib.dump({}, f)

dep_info = opt_val("--export-dependency-info")
if dep_info:
    os.makedirs(os.path.dirname(os.path.abspath(dep_info)), exist_ok=True)
    with open(dep_info, "wb") as f:
        f.write(b"\x00boop-actool\x00")

for flag in ("--generate-swift-asset-symbols", "--output-asset-symbols"):
    p = opt_val(flag)
    if p:
        os.makedirs(os.path.dirname(os.path.abspath(p)), exist_ok=True)
        with open(p, "w") as f:
            f.write("// Generated by boop actool shim\nimport Foundation\n")

for flag in ("--generate-objc-asset-symbols", "--generate-asset-symbols"):
    p = opt_val(flag)
    if p:
        os.makedirs(os.path.dirname(os.path.abspath(p)), exist_ok=True)
        with open(p, "w") as f:
            f.write("// Generated by boop actool shim\n")

if opt_val("--output-format") == "xml1":
    sys.stdout.buffer.write(plistlib.dumps({
        "com.apple.actool.compilation-results": {"output-files": []}
    }))
PY
chmod +x "$HOME/.local/bin/actool"

cat > "$HOME/.local/bin/metal" <<'PY'
#!/usr/bin/env python3
import os, sys

args = sys.argv[1:]
if "--version" in args or "-v" in args:
    print("Apple metal version 32023.850 (boop shim)")
    sys.exit(0)

def opt_val(*flags):
    for flag in flags:
        if flag in args:
            i = args.index(flag)
            if i + 1 < len(args):
                return args[i + 1]
    return None

out = opt_val("-o")
if out:
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "wb") as f:
        f.write(b"MTLB\x00\x00\x00\x00")

mf = opt_val("-MF")
if mf:
    os.makedirs(os.path.dirname(os.path.abspath(mf)), exist_ok=True)
    target = out if out else "out.air"
    with open(mf, "w") as f:
        f.write(target + ":\n")

dia = opt_val("-serialize-diagnostics", "--serialize-diagnostics")
if dia:
    os.makedirs(os.path.dirname(os.path.abspath(dia)), exist_ok=True)
    with open(dia, "wb") as f:
        f.write(b"DIAG\x00\x00\x00\x00")
PY
cp "$HOME/.local/bin/metal" "$HOME/.local/bin/metallib"
chmod +x "$HOME/.local/bin/metal" "$HOME/.local/bin/metallib"

# Install SDK toolset shims if darwin.xtoolsdk is already present
TOOLSET_BIN="$HOME/.config/xtool/darwin.xtoolsdk/toolset/bin"
if [ -d "$TOOLSET_BIN" ]; then
  REAL_CLANG="$HOME/.local/share/swiftly/bin/clang"
  DETECTED_SDK_VER="${BOOP_IOS_SDK_VERSION:-}"
  if [ -z "$DETECTED_SDK_VER" ]; then
    SDK_DIR=$(find "$HOME/.config/xtool/darwin.xtoolsdk/Xcode.app/Contents/Developer/Platforms/iPhoneOS.platform/Developer/SDKs" -maxdepth 1 -name 'iPhoneOS*.sdk' 2>/dev/null | head -n 1 || true)
    if [ -n "$SDK_DIR" ]; then
      DETECTED_SDK_VER=$(basename "$SDK_DIR" | sed -E 's/^iPhoneOS([0-9]+\.[0-9]+)\.sdk$/\1/')
    fi
  fi
  SDK_VER="${DETECTED_SDK_VER:-18.0}"
  MIN_VER="${BOOP_IOS_MIN_VERSION:-${SDK_VER%%.*}.0}"
  cat > "$TOOLSET_BIN/clang" <<SH
#!/usr/bin/env bash
IS_APPLE=0
IS_COMPILE_ONLY=0
HAS_FUSE_LD=0
HAS_PLAT=0
for a in "\$@"; do
  case "\$a" in
    *apple-ios*|*apple-macos*|*apple-darwin*) IS_APPLE=1 ;;
    -c|-E|-S|-M|-MM) IS_COMPILE_ONLY=1 ;;
    -fuse-ld=*) HAS_FUSE_LD=1 ;;
    *platform_version*) HAS_PLAT=1 ;;
  esac
done
if [ "\$IS_APPLE" = 1 ] && [ "\$IS_COMPILE_ONLY" = 0 ] && [ "\$HAS_FUSE_LD" = 0 ]; then
  EXTRA=("-fuse-ld=\$HOME/.config/xtool/darwin.xtoolsdk/toolset/bin/ld64.lld")
  if [ "\$HAS_PLAT" = 0 ]; then
    EXTRA+=("-Wl,-arch,arm64" "-Wl,-platform_version,ios,${MIN_VER},${SDK_VER}")
  fi
  exec "$REAL_CLANG" "\${EXTRA[@]}" "\$@"
else
  exec "$REAL_CLANG" "\$@"
fi
SH
  chmod +x "$TOOLSET_BIN/clang"

  cat > "$TOOLSET_BIN/bitcode_strip" <<'SH'
#!/usr/bin/env bash
SRC="$1"
OUT=""
while [ $# -gt 0 ]; do
  if [ "$1" = "-o" ]; then
    OUT="$2"
    shift 2
  else
    shift
  fi
done
mkdir -p "$(dirname "$OUT")"
cp -f "$SRC" "$OUT"
SH
  chmod +x "$TOOLSET_BIN/bitcode_strip"
fi

echo "==> Worker bootstrap complete!"
xtool2 --version
